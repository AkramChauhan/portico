/* Portico — interface translations.
 *
 * Keys are grouped by where they appear. Technical nouns are deliberately left
 * untranslated in every language: HTTPS, SSL, Caddy, cloudflared, dnsmasq,
 * PHP-FPM, Homebrew, npm and file paths are the words users of this tool
 * already know, and localising them would make instructions harder to follow,
 * not easier.
 *
 * The set is weighted for developers rather than for speakers overall: Indian
 * and French engineers overwhelmingly work in English, while Brazil and Japan
 * have large developer populations that do prefer localised software.
 *
 * All five languages here are left-to-right. Adding Arabic, Hebrew, Farsi or
 * Urdu would additionally require `dir="rtl"` handling and a mirrored layout,
 * which nothing here does yet.
 */

