let current = "en";

/// Resolve "auto" against the system locale, falling back to English.
export function resolveLanguage(setting) {
  if (setting && setting !== "auto" && STRINGS[setting]) return setting;
  const tag = (navigator.language || "en").toLowerCase();
  const base = tag.split("-")[0];
  return STRINGS[base] ? base : "en";
}

export function setLanguage(code) {
  current = STRINGS[code] ? code : "en";
  document.documentElement.lang = current;
}

export function currentLanguage() {
  return current;
}

/// Look up a key. Missing translations fall back to English rather than
/// showing a raw key, so a partial translation degrades gracefully.
export function t(key) {
  return STRINGS[current]?.[key] ?? STRINGS.en[key] ?? key;
}

/// Translate everything in the static markup that is tagged for it.
export function applyTranslations(root = document) {
  for (const node of root.querySelectorAll("[data-i18n]")) {
    node.textContent = t(node.dataset.i18n);
  }
  for (const node of root.querySelectorAll("[data-i18n-placeholder]")) {
    node.placeholder = t(node.dataset.i18nPlaceholder);
  }
  for (const node of root.querySelectorAll("[data-i18n-title]")) {
    const text = t(node.dataset.i18nTitle);
    node.title = text;
    node.setAttribute("aria-label", text);
  }
}
